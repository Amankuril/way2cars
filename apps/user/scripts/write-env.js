/**
 * Writes src/env.js from environment variables at build time (values are public, non-secret).
 *   W2C_API_BASE_URL=https://api.way2cars.in npm run build:release
 */
const fs = require('fs');
const path = require('path');

const apiBaseUrl = (process.env.W2C_API_BASE_URL || 'http://10.0.2.2:4000').replace(/\/+$/, '');
const env = process.env.W2C_ENV || (apiBaseUrl.startsWith('https://') ? 'production' : 'development');
if (env === 'production' && !apiBaseUrl.startsWith('https://')) {
  console.error('Production builds must use an https:// API URL.');
  process.exit(1);
}
// Same lookup as android/app/build.gradle: environment first, then android/local.properties.
function setting(key) {
  if (process.env[key]) return process.env[key];
  try {
    const line = fs.readFileSync(path.join(__dirname, '../android/local.properties'), 'utf8').split('\n').find((l) => l.startsWith(`${key}=`));
    return line ? line.slice(key.length + 1).trim() : '';
  } catch {
    return '';
  }
}
const out = `// Generated by scripts/write-env.js — do not edit or commit.\nexport const ENV = ${JSON.stringify({ apiBaseUrl, env, mapsEnabled: Boolean(setting('GOOGLE_MAPS_ANDROID_KEY')), builtAt: new Date().toISOString() }, null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, '../src/env.js'), out);
console.log(`env.js → ${apiBaseUrl} (${env})`);
